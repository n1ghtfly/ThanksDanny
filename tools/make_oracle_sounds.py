#!/usr/bin/env python3
"""Oracle 8-ball sounds (v3.34) -> Badge/oracle_sounds.h   (16 kHz mono int16, played with sosPlay)

    python tools/make_oracle_sounds.py          # writes the header
    python tools/make_oracle_sounds.py --wav    # also writes oracle_swirl.wav / oracle_reveal.wav to listen to

SWIRL  (1.45 s, while the marble spins): the liquid inside a magic 8-ball - low filtered noise whose
       brightness follows the swirl (up, then settling), with bubbles: short upward-gliding sine blips.
       It is shorter than the spin (ORA_SPIN_MS 1600) so the speaker is free for the reveal.
REVEAL (1.7 s, when the answer window opens): a mystical bell arpeggio, A - C# - E - A, each note a
       bell (inharmonic partials, exponential decay), a little shimmer on top.
All synthesised here - nothing third-party.
"""
import math
import sys
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Badge" / "oracle_sounds.h"
RATE = 16000
rng = np.random.default_rng(42)


def swirl(dur=1.45):
    n = int(dur * RATE)
    t = np.arange(n) / RATE
    x = t / dur
    # liquid: noise through a one-pole low-pass whose cutoff rises and falls with the swirl
    noise = rng.standard_normal(n)
    cutoff = 250 + 1400 * np.sin(np.pi * x) ** 1.5                 # Hz
    a = np.exp(-2 * np.pi * cutoff / RATE)
    y = np.zeros(n)
    acc = 0.0
    for i in range(n):
        acc = a[i] * acc + (1 - a[i]) * noise[i]
        y[i] = acc
    slosh = 0.6 + 0.4 * np.sin(2 * np.pi * (3 + 4 * (1 - x)) * t)   # waves, slowing down
    liquid = y / np.max(np.abs(y)) * slosh
    # bubbles: short sine blips gliding upward
    bub = np.zeros(n)
    tt = 0.03
    while tt < dur - 0.08:
        f0 = rng.uniform(350, 800)
        L = int(rng.uniform(0.025, 0.06) * RATE)
        k = np.arange(L) / RATE
        f = f0 * (1 + 2.5 * k / (L / RATE))                         # glide up
        ph = 2 * np.pi * np.cumsum(f) / RATE
        env = np.sin(np.pi * np.arange(L) / L) ** 2
        s = int(tt * RATE)
        bub[s:s + L] += np.sin(ph) * env * rng.uniform(0.4, 0.9)
        tt += rng.uniform(0.04, 0.13) * (1 + 1.5 * (tt / dur))     # fewer bubbles as it settles
    env = np.minimum(1, t / 0.08) * (1 - x) ** 0.7                  # fade in fast, out with the spin
    out = (0.55 * liquid + 0.45 * bub) * env
    return out


def reveal(dur=1.7):
    n = int(dur * RATE)
    t = np.arange(n) / RATE
    out = np.zeros(n)
    notes = [880.0, 1108.7, 1318.5, 1760.0]                         # A5 C#6 E6 A6
    for k, f in enumerate(notes):
        start = 0.09 * k
        tk = t - start
        on = tk >= 0
        tk = np.where(on, tk, 0)
        bell = np.zeros(n)
        for ratio, amp, tau in ((1.0, 1.0, 0.55), (2.76, 0.45, 0.22), (5.40, 0.22, 0.10), (2.0, 0.25, 0.35)):
            bell += amp * np.sin(2 * np.pi * f * ratio * tk) * np.exp(-tk / tau)
        attack = np.minimum(1, tk / 0.004)
        out += np.where(on, bell * attack, 0) * (0.9 - 0.1 * k)
    shimmer = np.sin(2 * np.pi * 3520 * t) * np.exp(-t / 0.5) * (0.5 + 0.5 * np.sin(2 * np.pi * 9 * t)) * 0.12
    out += shimmer
    out *= np.minimum(1, (dur - t) / 0.15)                          # no click at the end
    return out


def to_i16(x, peak=0.85):
    x = x / np.max(np.abs(x)) * peak
    return np.round(x * 32767).astype(np.int16)


def main():
    sw, rv = to_i16(swirl()), to_i16(reveal())
    L = ["// Generated by tools/make_oracle_sounds.py - do not edit by hand.", "#pragma once", "#include <stdint.h>", ""]
    for name, d in (("SND_ORA_SWIRL", sw), ("SND_ORA_REVEAL", rv)):
        L.append(f"#define {name}_LEN {len(d)}")
        L.append(f"static const int16_t {name}[{len(d)}] PROGMEM = {{")
        for i in range(0, len(d), 24):
            L.append("  " + ",".join(str(v) for v in d[i:i + 24]) + ",")
        L.append("};")
    OUT.write_text("\n".join(L) + "\n", encoding="ascii")
    print(f"wrote {OUT}: swirl {len(sw) / RATE:.2f} s, reveal {len(rv) / RATE:.2f} s, {(len(sw) + len(rv)) * 2 // 1024} kB")
    if "--wav" in sys.argv:
        for nm, d in (("oracle_swirl.wav", sw), ("oracle_reveal.wav", rv)):
            with wave.open(str(ROOT / nm), "wb") as w:
                w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(d.tobytes())
            print("wrote", nm)


if __name__ == "__main__":
    main()
