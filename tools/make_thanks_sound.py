#!/usr/bin/env python3
"""The "Thanks Danny!" voice for clap detection (v3.23) -> Badge/thanks_sound.h.

Input: any audio file ffmpeg can read (wav, mp3, m4a from a phone...). It is converted to 16 kHz mono,
the silence at both ends is trimmed, and it is normalised to -1 dBFS, then written as int16 PCM in
flash - the same format as the slap sounds (sos_sounds.h), played with sosPlay().

The default clip was made offline with Piper TTS (github.com/rhasspy/piper), voice en-us-ryan-high
(RyanSpeech dataset, CC BY-NC-SA 4.0 - fine for these non-commercial badges):
    echo "Thanks, Danny!" | piper -m en-us-ryan-high.onnx -f thanks.wav
Better still: record Danny saying it on a phone and run this script on that file.

Usage: python tools/make_thanks_sound.py thanks.wav [max_seconds]
"""
import subprocess
import sys
import wave
from array import array
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Badge" / "thanks_sound.h"
RATE = 16000


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    max_s = float(sys.argv[2]) if len(sys.argv) > 2 else 2.0
    tmp = Path(OUT.parent / "_thanks_tmp.wav")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-ac", "1", "-ar", str(RATE),
                    "-sample_fmt", "s16", str(tmp)], check=True)
    with wave.open(str(tmp)) as w:
        pcm = array("h", w.readframes(w.getnframes()))
    tmp.unlink()

    # Trim: drop leading/trailing samples quieter than 2% of the peak (keep 20 ms around speech).
    peak = max(1, max(abs(s) for s in pcm))
    loud = [i for i, s in enumerate(pcm) if abs(s) > peak * 0.02]
    pad = RATE // 50
    a, b = max(0, loud[0] - pad), min(len(pcm), loud[-1] + pad)
    pcm = pcm[a:b][: int(max_s * RATE)]

    # Normalise to -1 dBFS, with a 10 ms fade at both ends (no clicks).
    g = 0.89 * 32767 / peak
    fade = RATE // 100
    out = []
    for i, s in enumerate(pcm):
        f = min(1.0, i / fade, (len(pcm) - 1 - i) / fade)
        out.append(int(max(-32768, min(32767, round(s * g * f)))))

    lines = ["// Generated by tools/make_thanks_sound.py - do not edit by hand.", "#pragma once",
             "#include <stdint.h>", "", f"#define SND_THANKS_LEN {len(out)}",
             f"static const int16_t SND_THANKS[{len(out)}] = {{"]
    for i in range(0, len(out), 24):
        lines.append(",".join(str(v) for v in out[i:i + 24]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {OUT}: {len(out)} samples, {len(out) / RATE:.2f} s, {len(out) * 2} bytes of flash")


if __name__ == "__main__":
    main()
