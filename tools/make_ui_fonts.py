#!/usr/bin/env python3
"""UI fonts for the home screen and Settings (v3.14): DejaVu Sans Bold as Adafruit-GFX fonts.

The built-in 6x8 font only scales in whole steps (x1, x2, x3), so "10% bigger" needs a real
typeface. Each font here is sized so its CAPITAL height is 10% above the built-in text it
replaces (built-in caps are 7 px per scale step):

    UiSmall  replaces size 1 (caps  7 px) -> caps  8 px, v3.17:  9 px
    UiBig    replaces size 2 (caps 14 px) -> caps 15 px, v3.17: 17 px
    UiTitle  replaces size 3 (caps 21 px) -> caps 23 px, v3.17: 26 px

Output: Badge/ui_fonts.h (GFXfont structs, ASCII 0x20-0x7E, 1 bit per pixel).
DejaVu fonts: Bitstream Vera licence - free to embed and redistribute.
Usage: python tools/make_ui_fonts.py [path/to/DejaVuSans-Bold.ttf]
"""
import sys
from pathlib import Path
from PIL import ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT = Path(__file__).resolve().parent.parent / "Badge" / "ui_fonts.h"
FONTS = [("UiSmall", 9), ("UiBig", 17), ("UiTitle", 26)]   # v3.17: one step up from 8 / 15 / 23   # name, target cap height (px)


def cap_height(font):
    x0, y0, x1, y1 = font.getbbox("H", anchor="ls")
    return -y0


def pick_size(target):
    for px in range(6, 60):
        if cap_height(ImageFont.truetype(TTF, px)) >= target:
            return px
    raise SystemExit("no size reaches the target")


def main():
    # GFXglyph.bitmapOffset is a BYTE offset, and each glyph starts on a byte boundary in
    # Adafruit's format - so pack per glyph rather than as one long bit stream.
    out = ["// Generated by tools/make_ui_fonts.py - do not edit.", "#pragma once", ""]
    for name, target in FONTS:
        px = pick_size(target)
        font = ImageFont.truetype(TTF, px)
        data, glyphs = bytearray(), []
        for code in range(0x20, 0x7F):
            ch = chr(code)
            mask, (ox, oy) = font.getmask2(ch, mode="1", anchor="ls")
            w, h = mask.size
            adv = int(round(font.getlength(ch)))
            off = len(data)
            acc, n = 0, 0
            for y in range(h):
                for x in range(w):
                    acc = (acc << 1) | (1 if mask.getpixel((x, y)) else 0)
                    n += 1
                    if n == 8:
                        data.append(acc); acc, n = 0, 0
            if n:
                data.append(acc << (8 - n))
            glyphs.append((off, w, h, adv, ox, oy))
        asc, desc = font.getmetrics()
        cap = cap_height(font)
        out.append(f"// {name}: DejaVu Sans Bold {px} px, caps {cap} px (target {target}), line {asc + desc} px")
        out.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{")
        for i in range(0, len(data), 16):
            out.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{")
        for code, (off, w, h, adv, ox, oy) in zip(range(0x20, 0x7F), glyphs):
            out.append(f"  {{ {off}, {w}, {h}, {adv}, {ox}, {oy} }},  // 0x{code:02X}")
        out.append("};")
        out.append(f"static const GFXfont {name} PROGMEM = {{ (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x20, 0x7E, {asc + desc} }};")
        out.append(f"#define {name.upper()}_CAP {cap}")
        out.append("")
        print(f"{name:8s} {px:2d} px  caps {cap:2d} (target {target})  line {asc + desc}  {len(data)} bytes")
    OUT.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
